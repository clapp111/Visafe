-- ============================================================
-- 로그인 유지용 리프레시 토큰. 회원당 1개(마지막 로그인 기기)만 유효하다.
-- 토큰 원문은 저장하지 않고 SHA-256 해시만 저장한다. (DB가 유출되어도 토큰을 쓸 수 없음)
-- 기록이 아니라 세션 정보라 로그아웃 시 행을 삭제한다.
-- ============================================================

CREATE TABLE refresh_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  member_id BIGINT NOT NULL,
  token_hash CHAR(66) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
  CONSTRAINT uq_refresh_tokens__member_id UNIQUE (member_id),
  CONSTRAINT uq_refresh_tokens__token_hash UNIQUE (token_hash),
  CONSTRAINT ck_refresh_tokens__token_hash CHECK (token_hash ~ '^0x[0-9a-f]{64}$')
);
COMMENT ON TABLE refresh_tokens IS 'A. 리프레시 토큰 (회원당 1개)';
COMMENT ON COLUMN refresh_tokens.id IS 'ID';
COMMENT ON COLUMN refresh_tokens.member_id IS '회원';
COMMENT ON COLUMN refresh_tokens.token_hash IS '토큰 해시 (0x + SHA-256)';
COMMENT ON COLUMN refresh_tokens.expires_at IS '만료 일시';
COMMENT ON COLUMN refresh_tokens.created_at IS '생성 일시';
COMMENT ON COLUMN refresh_tokens.updated_at IS '수정 일시';

ALTER TABLE refresh_tokens ADD CONSTRAINT fk_refresh_tokens__member_id FOREIGN KEY (member_id) REFERENCES members (id);

CREATE TRIGGER trg_refresh_tokens__updated_at BEFORE UPDATE ON refresh_tokens FOR EACH ROW EXECUTE FUNCTION set_updated_at();
