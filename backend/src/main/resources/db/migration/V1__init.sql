-- 3) 역할 검사 (외래키만으로는 역할을 확인할 수 없음)
CREATE FUNCTION require_member_role(p_member_id BIGINT, p_role TEXT, p_what TEXT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF p_member_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM members WHERE id = p_member_id AND role = p_role) THEN
    RAISE EXCEPTION '%(id=%)는 % 역할이어야 합니다', p_what, p_member_id, p_role;
  END IF;
END $$;
CREATE FUNCTION check_contract_roles() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM require_member_role(NEW.employer_member_id, 'EMPLOYER', 'employer_member_id');
  PERFORM require_member_role(NEW.worker_member_id, 'WORKER', 'worker_member_id');
  RETURN NEW;
END $$;
CREATE TRIGGER trg_contracts__roles BEFORE INSERT OR UPDATE OF employer_member_id, worker_member_id ON contracts FOR EACH ROW EXECUTE FUNCTION check_contract_roles();
CREATE FUNCTION check_worker_profile_role() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM require_member_role(NEW.member_id, 'WORKER', 'member_worker_profiles.member_id');
  RETURN NEW;
END $$;
CREATE TRIGGER trg_member_worker_profiles__role BEFORE INSERT OR UPDATE OF member_id ON member_worker_profiles FOR EACH ROW EXECUTE FUNCTION check_worker_profile_role();
CREATE FUNCTION check_review_response_worker() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM translations t
    JOIN contract_versions v ON v.id = t.contract_version_id
    JOIN contracts k ON k.id = v.contract_id
    WHERE t.id = NEW.translation_id AND k.worker_member_id = NEW.worker_member_id
  ) THEN
    RAISE EXCEPTION '응답한 사람(id=%)이 이 계약의 근로자가 아닙니다', NEW.worker_member_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_review_responses__worker BEFORE INSERT ON review_responses FOR EACH ROW EXECUTE FUNCTION check_review_response_worker();
CREATE FUNCTION check_authority_reviewer() RETURNS trigger LANGUAGE plpgsql AS $$
