CREATE TABLE contracts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  contract_no CHAR(12) NOT NULL,
  confirmation_no CHAR(12) NULL,
  company_id BIGINT NOT NULL,
  employer_member_id BIGINT NOT NULL,
  worker_member_id BIGINT NOT NULL,
  previous_contract_id BIGINT NULL,
  doc_type VARCHAR(30) NOT NULL DEFAULT 'LABOR_CONTRACT',
  target_language CHAR(2) NOT NULL,
  stage VARCHAR(20) NOT NULL DEFAULT 'UPLOADED',
  status VARCHAR(20) GENERATED ALWAYS AS (CASE stage WHEN 'DONE' THEN 'CONFIRMED' WHEN 'ENDED' THEN 'TERMINATED' ELSE 'IN_PROGRESS' END) STORED,
  current_contract_version_id BIGINT NULL,
  requires_authority_review BOOLEAN NOT NULL DEFAULT false,
  confirmed_at TIMESTAMPTZ NULL,
  terminated_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_contracts PRIMARY KEY (id),
  CONSTRAINT uq_contracts__contract_no UNIQUE (contract_no),
  CONSTRAINT uq_contracts__confirmation_no UNIQUE (confirmation_no),
  CONSTRAINT ck_contracts__contract_no CHECK (contract_no ~ '^C-[0-9]{4}-[0-9]{5}$'),
  CONSTRAINT ck_contracts__confirmation_no CHECK (confirmation_no ~ '^VS-[2-9A-HJ-NP-Z]{4}-[2-9A-HJ-NP-Z]{4}$'),
  CONSTRAINT ck_contracts__doc_type CHECK (doc_type IN ('LABOR_CONTRACT')),
  CONSTRAINT ck_contracts__target_language CHECK (target_language ~ '^[a-z]{2}$'),
  CONSTRAINT ck_contracts__stage CHECK (stage IN ('UPLOADED', 'REVIEWING', 'TRANSLATING', 'AWAITING_WORKER', 'RETURNED', 'AUTHORITY_REVIEW', 'RECORDING', 'DONE', 'ENDED')),
  CONSTRAINT ck_contracts__parties_differ CHECK (employer_member_id <> worker_member_id),
  CONSTRAINT ck_contracts__previous_not_self CHECK (previous_contract_id <> id),
  CONSTRAINT ck_contracts__confirmed_fields CHECK ((stage IN ('DONE','ENDED')) = (confirmation_no IS NOT NULL AND confirmed_at IS NOT NULL)),
  CONSTRAINT ck_contracts__terminated_fields CHECK ((stage = 'ENDED') = (terminated_at IS NOT NULL))
);
COMMENT ON TABLE contracts IS 'B. 계약';
COMMENT ON COLUMN contracts.id IS 'ID';
COMMENT ON COLUMN contracts.contract_no IS '내부 계약 번호 (C-2026-04817)';
COMMENT ON COLUMN contracts.confirmation_no IS '공개 확인번호 (VS-7K3F-9QXM), 확정 시 발급';
COMMENT ON COLUMN contracts.company_id IS '사업주';
COMMENT ON COLUMN contracts.employer_member_id IS '등록한 고용주 계정 (사업주 소속)';
COMMENT ON COLUMN contracts.worker_member_id IS '근로자 계정';
COMMENT ON COLUMN contracts.previous_contract_id IS '대체한 이전 계약 (조건 변경 시)';
COMMENT ON COLUMN contracts.doc_type IS '문서 종류';
