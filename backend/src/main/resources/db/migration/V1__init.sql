-- 기준: 2026.11.17. / 테이블 22개 / 그룹 A~G
--
-- [이름 규칙]
--  테이블   : snake_case 복수형, 그룹 대표 이름을 접두어로 (contract_*, translation_*, review_*)
--  기본키   : id (BIGINT 자동 증가). 1:1 확장 테이블은 부모 FK가 곧 기본키
--  외래키   : <참조 테이블 단수>_id, 역할이 있으면 <역할>_<참조 단수>_id (employer_member_id)
--             사람을 가리키는 행위 컬럼은 <행위>_by_member_id (uploaded_by_member_id)
--  시각     : *_at TIMESTAMPTZ, 날짜는 *_date. 모든 테이블에 created_at, 바뀌는 테이블에 updated_at
--  해시     : CHAR(66) 0x + 소문자 16진수 64자리 (keccak256)
--  상태값   : VARCHAR + CHECK (대문자 스네이크)
--  제약 이름: pk_/uq_/ck_/fk_/ix_ + 테이블 + __ + 컬럼
--  삭제 정책: 기록 보존이 원칙이라 물리 삭제 없음. 외래키는 모두 기본값(NO ACTION)
